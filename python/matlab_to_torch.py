_MATLAB_CHECK = r"""function matlab_to_torch_check()
jobs = {
%s
};
for j = 1:size(jobs, 1)
    run_job(jobs{j, :});
end
end

function run_job(folder, infile, outfile)
cd(folder);
S = load(infile);
R = struct();
f = 1;
while isfield(S, sprintf('f%%d_name', f))
    key = sprintf('f%%d', f);
    fn = S.([key '_name']);
    clear(fn);
    out = [];
    for b = 1:S.B
        args = cell(1, S.([key '_nin']));
        for k = 1:numel(args)
            name = sprintf('%%s_in%%d', key, k);
            if isfield(S, name)
                if S.(sprintf('%%s_row%%d', key, k))
                    args{k} = S.(name)(:, b);
                else
                    args{k} = S.(name)(b, :);
                end
            end
        end
        y = feval(fn, args{:});
        out(:, b) = y(:);
    end
    R.(key) = out;
    f = f + 1;
end
save(outfile, '-struct', 'R');
end
"""


def check_against_matlab(jobs, matlab, batch, seed=0):
    """Evaluate the MATLAB exports sample by sample and compare with the generated functions.

    jobs: [(folder, module path, [main PyFunctions])]. Returns True if all outputs match."""
    import importlib.util
    import subprocess
    import tempfile

    import numpy as np
    import scipy.io
    import torch

    rng = np.random.default_rng(seed)
    tmp = Path(tempfile.mkdtemp(prefix="matlab_to_torch_"))
    expected, rows = [], []
    for j, (folder, module_path, pfs) in enumerate(jobs):
        spec = importlib.util.spec_from_file_location(f"_matlab_to_torch_check{j}", module_path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        data = {"B": float(batch)}
        for f, pf in enumerate(pfs, 1):
            key = f"f{f}"
            data[f"{key}_name"] = pf.mfunc.name
            data[f"{key}_nin"] = float(len(pf.mfunc.params))
            extra = {a: rng.uniform(0.5, 1.5, batch) for a in pf.extra_args}
            args = []
            for k, p in enumerate(pf.mfunc.params, 1):
                use = pf.input_use.get(p)
                if use is None:
                    if _py_ident(p) in pf.signature:
                        args.append(None)
                    continue
                if use[0] == "row":
                    a_mat = rng.uniform(-1.0, 1.0, (use[1], batch))
                    a_py = a_mat
                else:
                    a_mat = rng.uniform(0.5, 1.5, (batch, use[1]))
                    a_py = a_mat.copy()
                    for sym, (src, col) in pf.override_src.items():
                        if src == p:
                            a_mat[:, col - 1] = extra[OVERRIDES[sym]]  # what MATLAB sees
                            a_py[:, col - 1] = np.nan  # must not be read by the torch function
                data[f"{key}_in{k}"] = a_mat
                data[f"{key}_row{k}"] = float(use[0] == "row")
                args.append(torch.from_numpy(a_py))
            args += [torch.from_numpy(extra[a]) for a in pf.extra_args]
            out = getattr(module, pf.pyname)(*args)
            # flatten (r, c, B) column-major like MATLAB's y(:)
            flat = out.transpose(0, 1).reshape(-1, batch) if out.dim() == 3 else out
            expected.append((j, key, pf, tuple(out.shape), flat.detach().numpy()))
        scipy.io.savemat(tmp / f"in{j}.mat", data)
        rows.append(f"    '{Path(folder).resolve()}', '{tmp / f'in{j}.mat'}', '{tmp / f'out{j}.mat'}';")

    (tmp / "matlab_to_torch_check.m").write_text(_MATLAB_CHECK % "\n".join(rows), encoding="utf-8")
    print(f"running MATLAB ({matlab}) ...", flush=True)
    proc = subprocess.run([matlab, "-batch", f"addpath('{tmp}'); matlab_to_torch_check"],
                          capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stdout, proc.stderr, sep="\n")
        raise TranslationError("MATLAB check failed")

    ok_all = True
    results = {}
    for j, key, pf, shape, got in expected:
        ref = results.setdefault(j, scipy.io.loadmat(tmp / f"out{j}.mat"))[key]
        if ref.shape != got.shape:
            ok, msg = False, f"MATLAB {ref.shape} vs torch {got.shape}"
        else:
            err = np.max(np.abs(got - ref)) / max(1.0, np.max(np.abs(ref)))
            ok = bool(np.all(np.isfinite(got)) and err < 1e-10)
            msg = f"max rel. error {err:.1e}"
        ok_all &= ok
        print(f"  {'OK      ' if ok else 'MISMATCH'} {pf.pyname} {shape}: {msg}")
    return ok_all


