_TOKEN_RE = re.compile(r"""
    (?P<ws>\s+)
  | (?P<num>(?:\d+\.\d+|\d+\.(?![*/\\^'])|\d+|\.\d+)(?:[eE][+-]?\d+)?)
  | (?P<id>[A-Za-z_]\w*)
  | (?P<op>\.\*|\./|\.\\|\.\^|\.'|[-+*/\\^()\[\]{},;:'])
""", re.VERBOSE)

_FUNC_RE = re.compile(r"function\s+(\w+)\s*=\s*(\w+)\s*\(([^)]*)\)$")
_ASSIGN_RE = re.compile(r"(\w+)\s*=\s*(.+)$")
_DEAL_RE = re.compile(r"\[([\w,\s]+)\]\s*=\s*(\w+)\{:\}$")  # [a,b,c] = ct{:} (newer MATLAB releases)


def _tokenize(src):
    toks, pos, depth = [], 0, 0
    while pos < len(src):
        m = _TOKEN_RE.match(src, pos)
        if m is None:
            raise TranslationError(f"unexpected character in {src[pos:pos + 40]!r}")
        kind, text = m.lastgroup, m.group()
        pos = m.end()
        if kind == "ws":
            # MATLAB treats some spaces in [] / {} as element separators ([a -b] == [a, -b])
            if depth:
                raise TranslationError("whitespace inside [] or {} is ambiguous and not supported")
            continue
        depth += text in ("[", "{")
        depth -= text in ("]", "}")
        toks.append((kind, text))
    toks.append(("end", ""))
    return toks


class _Parser:
    """Recursive descent parser for the expression subset emitted by matlabFunction."""

    def __init__(self, src):
        self.toks = _tokenize(src)
        self.pos = 0

    def peek(self, offset=0):
        return self.toks[min(self.pos + offset, len(self.toks) - 1)][1]

    def take(self):
        self.pos += 1
        return self.toks[self.pos - 1][1]

    def expect(self, text):
        if self.peek() != text:
            raise TranslationError(f"expected {text!r} but found {self.peek()!r}")
        self.pos += 1

    def parse(self):
        node = self.additive()
        if self.toks[self.pos][0] != "end":
            raise TranslationError(f"unexpected {self.peek()!r}")
        return node

    def additive(self):
        first, rest = self.multiplicative(), []
        while self.peek() in ("+", "-"):
            op = self.take()
            rest.append((op, self.multiplicative()))
        return Chain("+", first, rest) if rest else first

    def multiplicative(self):
        first, rest = self.unary(), []
        while self.peek() in (".*", "*", "./", "/", ".\\", "\\"):
            op = self.take()
            if op in (".\\", "\\"):
                raise TranslationError("left division is not supported")
            rest.append(("*" if op in (".*", "*") else "/", self.unary()))
        return Chain("*", first, rest) if rest else first

    def unary(self):
        # MATLAB: unary minus binds weaker than power, -a.^b == -(a.^b)
        if self.peek() in ("+", "-"):
            op = self.take()
            operand = self.unary()
            return Neg(operand) if op == "-" else operand
        return self.power()

    def power(self):
        base = self.postfix()
        while self.peek() in (".^", "^"):  # left associative in MATLAB
            self.take()
            sign = self.take() if self.peek() in ("+", "-") else "+"
            exp = self.postfix()
            base = Pow(base, Neg(exp) if sign == "-" else exp)
        return base

    def postfix(self):
        node = self.primary()
        while True:
            if self.peek() in ("'", ".'"):
                raise TranslationError("transpose is not supported")
            if self.peek() == "(" and isinstance(node, Name):
                node = Apply(node.id, self.arguments("(", ")"))
            elif self.peek() == "{" and isinstance(node, Name):
                node = CellRef(node.id, self.arguments("{", "}"))
            else:
                return node

    def arguments(self, open_, close):
        self.expect(open_)
        args = []
        while self.peek() != close:
            if self.peek() == ":" and self.peek(1) in (",", close):
                self.take()
                args.append(Colon())
            else:
                args.append(self.additive())
            if self.peek() != ",":
                break
            self.take()
        self.expect(close)
        return args

    def primary(self):
        kind, text = self.toks[self.pos]
        if kind == "num":
            self.pos += 1
            return Num(text)
        if kind == "id":
            self.pos += 1
            return Name(text)
        if text == "(":
            self.pos += 1
            node = self.additive()
            self.expect(")")
            return node
        if text in ("[", "{"):
            return self.literal(text, "]" if text == "[" else "}")
        raise TranslationError(f"unexpected {text!r}")

    def literal(self, open_, close):
        self.expect(open_)
        rows, row = [], []
        while True:
            text = self.peek()
            if text == close:
                self.take()
                break
            if text in (";", ","):
                self.take()
                if text == ";":
                    rows.append(row)
                    row = []
                continue
            row.append(self.additive())
            if self.peek() not in (",", ";", close):
                raise TranslationError(f"expected ',', ';' or {close!r} but found {self.peek()!r}")
        rows.append(row)
        return Literal([r for r in rows if r], open_ == "{")


def _logical_lines(text):
    """Yield (lineno, statement) with comments removed, '...' continuations joined and
    line breaks inside [] / {} turned into row separators."""
    buf, depth, start = "", 0, 0
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.split("%", 1)[0].rstrip()
        continued = line.endswith("...")
        if continued:
            line = line[:-3]
        if not buf:
            start = lineno
        buf += line
        depth += sum(line.count(c) for c in "[{") - sum(line.count(c) for c in "]}")
        if continued:
            continue
        if depth > 0:
            buf += ";"
            continue
        stmt, buf = buf.strip(), ""
        if stmt:
            yield start, stmt
    if buf.strip():
        raise TranslationError(f"unterminated statement starting in line {start}")


def parse_mfile(path):
    funcs = []
    for lineno, stmt in _logical_lines(path.read_text(encoding="utf-8")):
        stmt = stmt.rstrip(";, \t")
        if stmt.startswith("function"):
            m = _FUNC_RE.match(stmt)
            if m is None:
                raise TranslationError(f"{path.name}:{lineno}: unsupported function header {stmt!r}")
            params = [p.strip() for p in m[3].split(",") if p.strip()]
            funcs.append(MFunction(m[2], m[1], params, [], path))
        elif (m := _DEAL_RE.match(stmt)) and funcs:
            names = [n.strip() for n in m[1].split(",")]
            funcs[-1].statements += [(lineno, n, f"{m[2]}{{{k}}}") for k, n in enumerate(names, 1)]
        elif stmt != "end":
            m = _ASSIGN_RE.match(stmt)
            if m is None or not funcs:
                raise TranslationError(f"{path.name}:{lineno}: unsupported statement {stmt[:60]!r}")
            funcs[-1].statements.append((lineno, m[1], m[2]))
    if not funcs:
        raise TranslationError(f"{path}: no function found")
    return funcs


