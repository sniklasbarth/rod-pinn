def _shape_str(shape):
    rows, cols = shape
    return f"({rows * cols}, B)" if rows == 1 or cols == 1 else f"({rows}, {cols}, B)"


def _output_shape(pf, by_name):
    shape = pf.out_shape
    while shape[0] == "sub":
        shape = by_name[shape[1]].out_shape
    return shape


def _docstring(pf, by_name):
    m = pf.mfunc
    text = m.path.read_text(encoding="utf-8")
    version = re.search(r"Symbolic Math Toolbox version ([\d.]*\d)", text)
    date = re.search(r"\d{2}-[A-Za-z]{3}-\d{4} \d{2}:\d{2}:\d{2}", text)
    origin = ", ".join(x for x in (version and f"Symbolic Math Toolbox {version[1]}", date and date[0]) if x)
    if not pf.is_main:
        return [f'"""Sub-function {m.name} of {m.path.name}; {", ".join(m.params)} is the list of its '
                f'cell entries. Returns {_shape_str(_output_shape(pf, by_name))}."""']

    lines = [f'"""Translated from {m.path.name}' + (f" ({origin})." if origin else "."), ""]
    names = INPUT_NAMES.get(m.name, [])
    for i, p in enumerate(m.params):
        if _py_ident(p) not in pf.signature:
            continue
        label = f"{p} ({names[i]})" if i < len(names) else p
        use = pf.input_use.get(p)
        if use is None:
            lines.append(f"{label}: unused")
        elif use[0] == "row":
            lines.append(f"{label}: (n, B) with n >= {use[1]}")
        else:
            lines.append(f"{label}: (B, n) or (1, n) with n >= {use[1]}")
    for arg in pf.extra_args:
        syms = [s for s, a in OVERRIDES.items() if a == arg and s in pf.override_src]
        cols = ", ".join(str(pf.override_src[s][1]) for s in syms)
        src = pf.override_src[syms[0]][0]
        lines.append(f"{arg}: replaces {', '.join(syms)} ({src} column{'s' * (len(syms) > 1)} {cols}); "
                     "scalar, (1,) or (B,)")
    lines.append(f"returns: {_shape_str(_output_shape(pf, by_name))}")
    lines.append('"""')
    return lines


def translate_folder(folder, tag, functions, taken):
    """Translate the requested exports of one generated folder; returns all PyFunctions."""
    result = []
    for mname, template in functions.items():
        path = folder / f"{mname}.m"
        if not path.is_file():
            raise TranslationError(f"{path} not found")
        mfuncs = parse_mfile(path)
        main = mfuncs[0]
        pynames = {main.name: template.format(tag=tag)}
        for sub in mfuncs[1:]:
            name = f"{sub.name}_{tag}"
            pynames[sub.name] = name if name not in taken else f"{sub.name}_{mname.strip('_')}_{tag}"
        for name in pynames.values():
            if name in taken:
                raise TranslationError(f"python function name {name} is generated twice (use --tag)")
            taken.add(name)
        subs = {s.name: pynames[s.name] for s in mfuncs[1:]}
        pfs = [_FunctionTranslator(f, pynames[f.name], subs, OVERRIDES, f is main).translate()
               for f in mfuncs]
        by_name = {pf.mfunc.name: pf for pf in pfs}
        for pf in pfs:
            pf.doc = _docstring(pf, by_name)
        result += pfs
    return result


def build_module(pfs, sources):
    out = [MODULE_HEADER.format(sources="\n".join(f"    {s}" for s in sources)).rstrip("\n")]
    for pf in pfs:
        out += ["", "", f"def {pf.pyname}({', '.join(pf.signature)}):"]
        out += [f"    {line}" if line else "" for line in pf.doc + pf.body]
    return "\n".join(out) + "\n"


def default_tag(folder):
    # folder names of local_frame_formulation (N_7_export_...) or of this repository (TRO_N_7)
    m = re.match(r"(?:TRO_)?N_(\d+)(?:_Ng_(\d+))?", folder.name)
    if m is None:
        raise TranslationError(f"cannot derive N from folder name {folder.name!r}, use --tag")
    return f"N{m[1]}" + (f"_Ng{m[2]}" if m[2] else "")


