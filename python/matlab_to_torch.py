@dataclass
class Scalar:
    code: str
    prec: int
    const: bool = False


@dataclass
class Mat:
    rows: int
    cols: int
    elems: list  # column-major [(code, ref)], ref = (python list name, index) or None


@dataclass
class SubCall:  # result of a call to a sub-function (already a stacked tensor)
    func: str  # python name
    sub: str  # MATLAB name
    args: list  # per argument: code string, or list of codes for a cell array


@dataclass
class CellVal:
    items: list


@dataclass
class PyFunction:
    mfunc: MFunction
    pyname: str
    signature: list
    body: list
    is_main: bool
    input_use: dict  # MATLAB input -> [mode ("row"/"col"), max index]
    override_src: dict  # overridden symbol -> (MATLAB input, column)
    extra_args: list
    out_shape: tuple  # MATLAB (rows, cols) or ("sub", MATLAB sub-function name)
    doc: list = field(default_factory=list)


def _py_ident(name):
    return name + "_" if keyword.iskeyword(name) or name in ("torch", "math", "abs") else name


def _py_number(text):
    return text + "0" if text.endswith(".") else text


def _paren(value, min_prec):
    return value.code if value.prec >= min_prec else f"({value.code})"


def _vcat(a, b):
    if a.cols != b.cols:
        raise TranslationError(f"vertical concatenation of {a.rows}x{a.cols} and {b.rows}x{b.cols}")
    elems = []
    for j in range(a.cols):
        elems += a.elems[j * a.rows:(j + 1) * a.rows] + b.elems[j * b.rows:(j + 1) * b.rows]
    return Mat(a.rows + b.rows, a.cols, elems)


def _wrap(items, indent, width=100):
    lines, cur = [], ""
    for item in items:
        piece = item + ","
        if cur and len(indent) + len(cur) + 1 + len(piece) > width:
            lines.append(indent + cur)
            cur = piece
        else:
            cur = f"{cur} {piece}" if cur else piece
    if cur:
        lines.append(indent + cur)
    return lines


class _FunctionTranslator:
    def __init__(self, mfunc, pyname, subfunctions, overrides, is_main):
        self.m = mfunc
        self.pyname = pyname
        self.subfunctions = subfunctions  # MATLAB name -> python name
        self.overrides = overrides if is_main else {}
        self.is_main = is_main
        self.params = set(mfunc.params)
        self.scope = {}
        self.list_len = {}
        self.body = []
        self.input_use = {}
        self.override_src = {}
        self.out_shape = None

    def translate(self):
        for lineno, lhs, rhs in self.m.statements:
            try:
                self.assign(lhs, _Parser(rhs).parse())
            except TranslationError as err:
                raise TranslationError(f"{self.m.path.name}:{lineno}: {err}") from None
        if self.out_shape is None:
            raise TranslationError(f"{self.m.path.name}: output {self.m.output} of {self.m.name} is never assigned")
        self.body.append(f"return {_py_ident(self.m.output)}")

        if self.is_main:
            used = [i for i, p in enumerate(self.m.params) if p in self.input_use]
            signature = [_py_ident(p) for p in self.m.params[:max(used) + 1]] if used else []
        else:
            signature = [_py_ident(p) for p in self.m.params]
        used_args = {self.overrides[s] for s in self.override_src}
        extra = [a for a in dict.fromkeys(self.overrides.values()) if a in used_args]
        return PyFunction(self.m, self.pyname, signature + extra, self.body, self.is_main,
                          self.input_use, self.override_src, extra, self.out_shape)

    # -- statements

    def assign(self, lhs, node):
        if lhs in self.params:
            raise TranslationError(f"assignment to input {lhs}")
        target = _py_ident(lhs)
        if lhs in self.overrides and isinstance(node, Apply) and node.name in self.params:
            self.index_input(node.name, node.args)
            if not isinstance(node.args[0], Colon):
                raise TranslationError(f"{lhs} is overridden but not read from a parameter column")
            self.override_src[lhs] = (node.name, self.int_literal(node.args[1]))
            self.body.append(f"{target} = {self.overrides[lhs]}")
            self.scope[lhs] = Scalar(target, ATOM)
            return

        value = self.value(node)
        if lhs == self.m.output:
            self.emit_output(target, value)
        elif isinstance(value, Mat):
            self.body.append(f"{target} = [{', '.join(code for code, _ in value.elems)}]")
            self.list_len[target] = len(value.elems)
            self.scope[lhs] = Mat(value.rows, value.cols,
                                  [(f"{target}[{k}]", (target, k)) for k in range(len(value.elems))])
        elif isinstance(value, Scalar):
            self.body.append(f"{target} = {value.code}")
            self.scope[lhs] = Scalar(target, ATOM, value.const)
        else:
            raise TranslationError(f"unsupported assignment to {lhs}")

    def emit_output(self, target, value):
        if isinstance(value, SubCall):
            self.body += self.call_lines(target, value)
            self.out_shape = ("sub", value.sub)
            return
        mat = self.as_mat(value)
        suffix = ""
        if mat.rows > 1 and mat.cols > 1:
            # entries are stacked in MATLAB's column-major order -> (r, c, B)
            suffix = f".reshape({mat.cols}, {mat.rows}, -1).transpose(0, 1)"
        items = self.compress(mat.elems)
        line = f"{target} = _stack_entries([{', '.join(items)}]){suffix}"
        if len(line) <= 96:
            self.body.append(line)
        else:
            self.body += [f"{target} = _stack_entries(["] + _wrap(items, "    ") + [f"]){suffix}"]
        self.out_shape = (mat.rows, mat.cols)

    def call_lines(self, target, call):
        lines = [f"{target} = {call.func}("]
        for arg in call.args:
            if isinstance(arg, list):
                lines += ["    ["] + _wrap(arg, "        ") + ["    ],"]
            else:
                lines.append(f"    {arg},")
        return lines + [")"]

    def compress(self, elems):
        """Replace complete runs lst[0], lst[1], ... of a generated list by *lst."""
        items, k = [], 0
        while k < len(elems):
            code, ref = elems[k]
            if ref is not None and ref[1] == 0:
                name, n = ref[0], self.list_len[ref[0]]
                if [r for _, r in elems[k:k + n]] == [(name, i) for i in range(n)]:
                    items.append("*" + name)
                    k += n
                    continue
            items.append(code)
            k += 1
        return items

    # -- expressions

    def value(self, node):
        if isinstance(node, Num):
            return Scalar(_py_number(node.text), ATOM, True)
        if isinstance(node, Name):
            if node.id in self.scope:
                return self.scope[node.id]
            if node.id in CONSTANTS:
                return Scalar(CONSTANTS[node.id], ATOM, True)
            if node.id in self.params:
                raise TranslationError(f"input {node.id} is used without indexing")
            raise TranslationError(f"undefined variable {node.id}")
        if isinstance(node, Neg):
            operand = self.scalar(node.operand)
            return Scalar("-" + _paren(operand, POW), UNARY, operand.const)
        if isinstance(node, Chain):
            prec = ADD if node.op == "+" else MUL
            parts, const = [], True
            for k, (op, sub) in enumerate([(None, node.first)] + node.rest):
                v = self.scalar(sub)
                const &= v.const
                # left operand may have the same precedence, right operands need more
                # (keeps MATLAB's left-to-right evaluation order)
                code = _paren(v, prec if k == 0 else prec + 1)
                parts.append(code if op is None else op + code)
            return Scalar("".join(parts), prec, const)
        if isinstance(node, Pow):
            base, exp = self.scalar(node.base), self.scalar(node.exp)
            return Scalar(f"{_paren(base, ATOM)}**{_paren(exp, UNARY)}", POW, base.const and exp.const)
        if isinstance(node, Apply):
            return self.apply(node)
        if isinstance(node, CellRef):
            if node.name not in self.params or len(node.args) != 1:
                raise TranslationError(f"unsupported cell access {node.name}{{...}}")
            return Scalar(f"{_py_ident(node.name)}[{self.int_literal(node.args[0]) - 1}]", ATOM)
        if isinstance(node, Literal):
            if node.cell:
                return CellVal([self.value(x) for row in node.rows for x in row])
            return self.matrix(node)
        raise TranslationError(f"unsupported expression {node}")

    def scalar(self, node):
        value = self.value(node)
        if not isinstance(value, Scalar):
            raise TranslationError("matrix-valued operand in a scalar expression is not supported")
        return value

    def as_mat(self, value):
        if isinstance(value, Mat):
            return value
        if isinstance(value, Scalar):
            return Mat(1, 1, [(value.code, None)])
        raise TranslationError("expected a matrix")

    def int_literal(self, node):
        if not isinstance(node, Num) or not re.fullmatch(r"\d+(\.0*)?", node.text):
            raise TranslationError(f"expected an integer literal, found {node}")
        return int(float(node.text))

    def index_input(self, name, args):
        if len(args) != 2:
            raise TranslationError(f"unsupported indexing of {name}")
        if isinstance(args[1], Colon) and not isinstance(args[0], Colon):
            mode, k = "row", self.int_literal(args[0])
            code = f"{_py_ident(name)}[{k - 1}, :]"
        elif isinstance(args[0], Colon) and not isinstance(args[1], Colon):
            mode, k = "col", self.int_literal(args[1])
            code = f"{_py_ident(name)}[:, {k - 1}]"
        else:
            raise TranslationError(f"unsupported indexing of {name}")
        use = self.input_use.setdefault(name, [mode, 0])
        if use[0] != mode:
            raise TranslationError(f"{name} is indexed both by rows and by columns")
        use[1] = max(use[1], k)
        return Scalar(code, ATOM)

    def apply(self, node):
        name, args = node.name, node.args
        if name in self.params:
            return self.index_input(name, args)
        if name in self.scope:
            raise TranslationError(f"indexing of local variable {name} is not supported")
        if name == "reshape":
            mat = self.as_mat(self.value(args[0]))
            dims = args[1:]
            if len(dims) == 1 and isinstance(dims[0], Literal):
                dims = [x for row in dims[0].rows for x in row]
            dims = [self.int_literal(d) for d in dims]
            if len(dims) != 2 or dims[0] * dims[1] != len(mat.elems):
                raise TranslationError(f"invalid reshape of {len(mat.elems)} elements to {dims}")
            return Mat(dims[0], dims[1], mat.elems)
        if name in self.subfunctions:
            call_args = []
            for arg in args:
                v = self.value(arg)
                if isinstance(v, CellVal):
                    call_args.append([self.as_scalar(x).code for x in v.items])
                else:
                    call_args.append(self.as_scalar(v).code)
            return SubCall(self.subfunctions[name], name, call_args)
        if name in ELEMENTARY:
            vals = [self.scalar(a) for a in args]
            torch_fn, const_fn = ELEMENTARY[name]
            if all(v.const for v in vals) and const_fn:
                return Scalar(f"{const_fn}({', '.join(v.code for v in vals)})", ATOM, True)
            if len(vals) > 1 and any(v.const for v in vals):
                raise TranslationError(f"{name} with mixed constant and tensor arguments is not supported")
            return Scalar(f"{torch_fn}({', '.join(v.code for v in vals)})", ATOM)
        raise TranslationError(f"unknown function {name}")

    def as_scalar(self, value):
        if not isinstance(value, Scalar):
            raise TranslationError("only scalar entries are supported in sub-function arguments")
        return value

    def matrix(self, node):
        result = None
        for row in node.rows:
            mats = [m for m in (self.as_mat(self.value(x)) for x in row) if m.elems]
            if not mats:
                continue
            if any(m.rows != mats[0].rows for m in mats):
                raise TranslationError("horizontal concatenation of matrices with different row counts")
            row_mat = Mat(mats[0].rows, sum(m.cols for m in mats), [e for m in mats for e in m.elems])
            result = row_mat if result is None else _vcat(result, row_mat)
        return result if result is not None else Mat(0, 0, [])


