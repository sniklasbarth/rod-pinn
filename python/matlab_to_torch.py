#!/usr/bin/env python3
"""Translate the matlabFunction exports of SymCosseratRod (c_.m, eta_pls.m, u_p.m)
into batch-capable PyTorch functions.

This generates the physics of the PINN loss (python/PINN_ODE_loss_functions_N7.py) from the
model export of step 1 (matlab/model/TRO_N_7). The generated functions follow the conventions
of the originally hand-written translations used for the paper (B = batch size):

    MATLAB                        PyTorch
    in1(i,:)   (states, ...)  ->  in1[i-1, :]   input of shape (n, B)
    in6(:,j)   (parameters)   ->  in6[:, j-1]   input of shape (B, n_p) or (1, n_p)
    vector output             ->  (n, B)
    reshape(..., r, c)        ->  (r, c, B)     e.g. eta_pls: (6, n_nodes, B)

C_4 and C_5 are taken from the extra argument `bend_compliance` and M_tip from
`tip_mass` (scalar, (1,) or (B,) tensors) instead of the parameter vector.
MATLAB inputs that are never used (e.g. in7 of c_.m) are dropped, so for N = 7

    implicit_ode_and_boundary_values_3D_N7_gravity(in1, ..., in6, bend_compliance, tip_mass)
    eta_pls_3D_N7(in1, in2, in3, bend_compliance)
    external_loads_3D_N7(in1, in2, in3, bend_compliance)

have the same signatures as the hand-written versions. The N-independent functions
(actuation_model_pressure, gravity, SO3_*) are not generated, they are part of
python/PINN_ODE_loss_functions.py.

The translation itself only needs the Python standard library. --check additionally
needs numpy, scipy, torch and a MATLAB installation; it evaluates the original .m files
sample by sample in MATLAB and compares them with the generated batch functions.

Usage (from the repository root, after step 1):
    python python/matlab_to_torch.py matlab/model/TRO_N_7
    python python/matlab_to_torch.py matlab/model/TRO_N_7 --check --matlab /path/to/matlab

Author: Johann Licher (IMES, Leibniz Universitaet Hannover)
"""
